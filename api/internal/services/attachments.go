// Limits — must match website/src/lib/services/attachments.ts.
const (
	MaxAttachmentBytes      = 5 * 1024 * 1024   // 5 MB per file
	MaxAttachmentsPerDevice = 5                 // 5 attachments / device
	MaxUploadBytesPerUser   = 100 * 1024 * 1024 // 100 MB total / user
)

// InboxStorageSegment is the reserved first path segment for an attachment that
// is not filed to a device yet (migration 0018). Blobs keep the historical
// `<deviceId>/<uuid>.enc` layout once filed; an inbox row lives under
// `_inbox/<uuid>.enc`, and filing renames the blob with it.
//
// `_inbox` cannot collide with a real device id: ids are generated by the server
// (cuid) and the backup importer refuses a payload device using this name.
const InboxStorageSegment = "_inbox"

// AttachmentError carries a code → HTTP status mapping that the handler can
// translate without coupling to the store package directly.
//
// i18n: the code is contract and does not move with the language. Only the
// words do, and they are finished here rather than at the handler, because every
// function below has the request context in scope (same shape as the
// subscriptions slice: ErrNotFound(i18n.Text(ctx, …))).
type AttachmentError struct {
	Code    string // "bad_input" | "not_found" | "limit_reached" | "internal_error"
	Message string
}

func (e *AttachmentError) Error() string { return e.Message }

func badInput(msg string) error     { return &AttachmentError{Code: "bad_input", Message: msg} }
func notFound(msg string) error     { return &AttachmentError{Code: "not_found", Message: msg} }
func limitReached(msg string) error { return &AttachmentError{Code: "limit_reached", Message: msg} }
func internalErr(msg string) error  { return &AttachmentError{Code: "internal_error", Message: msg} }

// filesText renders a message produced by internal/files in the request's
// language.
//
// internal/files deliberately knows nothing about languages: it is a low-level
// package (MIME sniffing, AES-GCM, path safety) called from two domains — the
// attachment pipeline here and AI receipt extraction in internal/handlers/ai.go —
// and it has no request context of its own. Its error TEXT is therefore the
// Vietnamese source and doubles as the catalog key (internal/i18n/catalog.go),
// and the caller that owns a request renders it:
//
//	services.Upload   → i18n.Text(ctx, err.Error())   (converted, this wave)
//	handlers/ai.go    → err.Error()                   (wave 4, Vietnamese verbatim)
//
// So adding the entry changes nothing for the AI path: an unconverted call site
// that never asks the catalog keeps sending exactly the bytes it sent before.
// (This is also why no entry exists for mime.go's "file trống": Upload rejects an
// empty body with "File trống" before DetectAndValidate can see it, so from this
// package the key is unreachable, and an unreachable catalog entry is dead weight
// — the same reason wave 2 dropped the wishlist singular.)
func filesText(ctx context.Context, err error) string {
	return i18n.Text(ctx, err.Error())
}

// AsAttachmentError returns the typed error if err is one, allowing handlers
// to assert with errors.As against this concrete type.
func AsAttachmentError(err error) (*AttachmentError, bool) {
	var ae *AttachmentError
	if errors.As(err, &ae) {
		return ae, true
	}
	return nil, false
}

// ListAttachmentsByDevice returns attachments owned by userID under deviceID.
// If the device is missing or not owned by the user, returns notFound.
func ListAttachmentsByDevice(ctx context.Context, db *pgxpool.Pool, userID, deviceID string) ([]store.Attachment, error) {
	q := store.New(db)
	dev, err := q.GetDeviceByID(ctx, store.GetDeviceByIDParams{ID: deviceID, UserId: userID})
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return nil, notFound(i18n.Text(ctx, "Thiết bị không tồn tại"))
		}
		return nil, fmt.Errorf("get device: %w", err)
	}
	_ = dev
	rows, err := q.ListAttachmentsByDevice(ctx, store.ListAttachmentsByDeviceParams{
		DeviceId: &deviceID,
		UserId:   userID,
	})
	if err != nil {
		return nil, fmt.Errorf("list attachments: %w", err)
	}
	return rows, nil
}

// GetAttachmentForUser returns an attachment if and only if userID owns it.
// Since migration 0018 ownership is stored on the row ("userId"), so this covers
// both a device-filed attachment and an inbox item. Returns notFound on any miss
// (no ID enumeration).
func GetAttachmentForUser(ctx context.Context, db *pgxpool.Pool, userID, attachmentID string) (store.Attachment, error) {
	q := store.New(db)
	att, err := q.GetAttachmentByID(ctx, store.GetAttachmentByIDParams{
		ID:     attachmentID,
		UserId: userID,
	})
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return store.Attachment{}, notFound(i18n.Text(ctx, "Không tìm thấy file"))
		}
		return store.Attachment{}, fmt.Errorf("get attachment: %w", err)
	}
	return att, nil
}

// ListInbox returns the caller's unassigned attachments, newest first. These are
// the same rows the device endpoints return, just not filed anywhere yet: no
// device data is joined in.
func ListInbox(ctx context.Context, db *pgxpool.Pool, userID string) ([]store.Attachment, error) {
	rows, err := store.New(db).ListInboxAttachments(ctx, userID)
	if err != nil {
		return nil, fmt.Errorf("list inbox: %w", err)
	}
	return rows, nil
}

// FileAttachment files an attachment under deviceID, or returns it to the inbox
// when deviceID is nil.
//
// Rules (frozen contract):
//   - 404 when the attachment is not the caller's or the device is not the
//     caller's (notFound, never 403);
//   - 409 LIMIT_REACHED when the TARGET device already holds
//     MaxAttachmentsPerDevice filed attachments — reusing the same error code
//     clients already handle on other write paths;
//   - re-filing an already-filed attachment to a DIFFERENT device is allowed and
//     counts against the target's cap;
//   - re-filing to the SAME device is an idempotent no-op and must not 409
//     against the item's own slot;
//   - an inbox item consumes no device slot, so this is the only place the cap
//     can be hit by an item that was not already filed.
//
// The blob is renamed to follow the row (`<deviceId>/…` ⇄ `_inbox/…`) so
// storagePath — which travels in the backup payload — keeps pointing at the
// bytes. A blob that is already missing does not block the assignment: the row
// still moves, and export reports it through missingAttachmentIds exactly like
// any other missing blob.
func FileAttachment(ctx context.Context, db *pgxpool.Pool, userID, attachmentID string, deviceID *string) (store.Attachment, error) {
	// Attachment ownership is checked BEFORE the target id's shape, so an id the
	// caller does not own is a 404 even when the requested deviceId is malformed —
	// the endpoint must never confirm that a foreign attachment exists.
	q := store.New(db)
	att, err := q.GetAttachmentByID(ctx, store.GetAttachmentByIDParams{
		ID:     attachmentID,
		UserId: userID,
	})
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return store.Attachment{}, notFound(i18n.Text(ctx, "Không tìm thấy file"))
		}
		return store.Attachment{}, fmt.Errorf("get attachment: %w", err)
	}

	if deviceID != nil && !files.SafeSegment(*deviceID) {
		return store.Attachment{}, badInput(i18n.Text(ctx, "Device không hợp lệ"))
	}

	// Same destination: success without consuming a slot or touching the blob.
	// This is what makes "file it again to the device it is already on" safe when
	// that device is full — the item is one of the five, not a sixth.
	if (att.DeviceId == nil && deviceID == nil) ||
		(att.DeviceId != nil && deviceID != nil && *att.DeviceId == *deviceID) {
		return att, nil
	}

	if deviceID != nil {
		// Target device ownership. 404 for the same reason as the attachment
		// lookup: an id the caller does not own must not be confirmed to exist.
		if _, derr := q.GetDeviceByID(ctx, store.GetDeviceByIDParams{ID: *deviceID, UserId: userID}); derr != nil {
			if errors.Is(derr, pgx.ErrNoRows) {
				return store.Attachment{}, notFound(i18n.Text(ctx, "Thiết bị không tồn tại"))
			}
			return store.Attachment{}, fmt.Errorf("get device: %w", derr)
		}
		count, cerr := q.CountAttachmentsByDevice(ctx, deviceID)
		if cerr != nil {
			return store.Attachment{}, fmt.Errorf("count attachments: %w", cerr)
		}
		if count >= int64(MaxAttachmentsPerDevice) {
			// *Error (not AttachmentError) on purpose: LIMIT_REACHED must be 409
			// on this endpoint. Upload's older `limit_reached` stays a 400 (see
			// handlers.writeAttachmentError) so its behaviour does not move.
			return store.Attachment{}, &Error{
				Code:    "LIMIT_REACHED",
				Message: i18n.Text(ctx, "Tối đa 5 file/thiết bị"),
			}
		}
	}

	oldSegment := InboxStorageSegment
	if att.DeviceId != nil {
		oldSegment = *att.DeviceId
	}
	newSegment := InboxStorageSegment
	if deviceID != nil {
		newSegment = *deviceID
	}
	newPath := att.StoragePath
	if oldSegment != newSegment {
		var merr error
		newPath, merr = files.MoveEncrypted(
			files.PrivateUploadRoot(), att.StoragePath, newSegment, filepath.Base(att.StoragePath))
		if merr != nil && !os.IsNotExist(merr) {
			return store.Attachment{}, internalErr(i18n.Text(ctx, "Lỗi di chuyển file"))
		}
		if merr != nil {
			slog.Warn("attachment blob missing while filing",
				"err", merr, "attachmentId", attachmentID, "from", att.StoragePath, "to", newPath)
		}
	}

	updated, uerr := q.AssignAttachmentToDevice(ctx, store.AssignAttachmentToDeviceParams{
		ID:          attachmentID,
		UserId:      userID,
		DeviceId:    deviceID,
		StoragePath: newPath,
	})
	if uerr != nil {
		// Put the blob back if the row did not move, so storagePath never points
		// at a file that is not there.
		if oldSegment != newSegment {
			_, _ = files.MoveEncrypted(
				files.PrivateUploadRoot(), newPath, oldSegment, filepath.Base(newPath))
		}
		if errors.Is(uerr, pgx.ErrNoRows) {
			return store.Attachment{}, notFound(i18n.Text(ctx, "Không tìm thấy file"))
		}
		return store.Attachment{}, fmt.Errorf("assign attachment: %w", uerr)
	}
	return updated, nil
}

// UploadAttachmentInput is the input bundle for Upload.
type UploadAttachmentInput struct {
	// DeviceID is the destination device, or nil for an inbox item. Everything
	// else about the pipeline (MIME whitelist, 5 MB cap, encryption, the 100 MB
	// per-user total) is identical for the two cases; only the per-device count
	// and the storage segment differ.
	DeviceID    *string
	FileName    string
	DeclaredCT  string // multipart Content-Type, may be empty
	Body        []byte
	Description *string
}

// Upload handles the full pipeline: ownership check, limit checks, MIME +
// magic-byte validation, optional resize, encryption, write to disk, DB row.
//
// With in.DeviceID nil the row is created as an inbox item (deviceId NULL) owned
// by userID and no device ownership/count is consulted. With a device id the
// behaviour is byte-for-byte the pre-0018 path: same checks, same errors, same
// 5-file ceiling.
//
// On any error before encryption the buffers are dropped and nothing is
// written. Errors after the disk write attempt to clean up the orphan blob.
//
// i18n: every message below is the EXISTING Vietnamese literal wrapped in
// `i18n.Text(ctx, …)`; Vietnamese stays the original and only gains an English
// column in internal/i18n/catalog.go. The two messages that come from
// internal/files and internal/files' own errors are rendered with `filesText`,
// so the same catalog entry serves this path without changing what the
// unconverted AI handler sends. No Code changes: an upload that refused with
// `bad_input` before still refuses with `bad_input`, in either language.
func Upload(ctx context.Context, db *pgxpool.Pool, userID string, in UploadAttachmentInput) (store.Attachment, error) {
	if in.DeviceID != nil && !files.SafeSegment(*in.DeviceID) {
		return store.Attachment{}, badInput(i18n.Text(ctx, "Device không hợp lệ"))
	}
	if len(in.Body) == 0 {
		return store.Attachment{}, badInput(i18n.Text(ctx, "File trống"))
	}
	if len(in.Body) > MaxAttachmentBytes {
		return store.Attachment{}, badInput(i18n.Text(ctx, "File vượt quá 5MB"))
	}

	q := store.New(db)
	if in.DeviceID != nil {
		// Ownership.
		if _, err := q.GetDeviceByID(ctx, store.GetDeviceByIDParams{ID: *in.DeviceID, UserId: userID}); err != nil {
			if errors.Is(err, pgx.ErrNoRows) {
				return store.Attachment{}, notFound(i18n.Text(ctx, "Thiết bị không tồn tại"))
			}
			return store.Attachment{}, fmt.Errorf("get device: %w", err)
		}

		// Per-device count. Inbox items have deviceId NULL and are not counted by
		// this query, which is exactly rule 6.
		count, err := q.CountAttachmentsByDevice(ctx, in.DeviceID)
		if err != nil {
			return store.Attachment{}, fmt.Errorf("count attachments: %w", err)
		}
		if count >= int64(MaxAttachmentsPerDevice) {
			// A single key, not a pair: the ceiling is the fixed constant 5, so
			// "1 file/thiết bị" can never be produced (see the catalog comment).
			return store.Attachment{}, limitReached(i18n.Text(ctx, "Tối đa 5 file/thiết bị"))
		}
	}

	// MIME detect + whitelist + magic-byte parity.
	mime, err := files.DetectAndValidate(in.Body, in.DeclaredCT)
	if err != nil {
		return store.Attachment{}, badInput(filesText(ctx, err))
	}

	// Resize (best-effort; falls back to original bytes on non-fatal codec
	// hiccups for gif/webp).
	processed, err := files.MaybeResize(in.Body, mime)
	if err != nil {
		return store.Attachment{}, badInput(i18n.Text(ctx, "Không xử lý được ảnh, file có thể đã hỏng"))
	}

	// Per-user total bytes cap (use processed length so resize savings count).
	used, err := q.SumAttachmentBytesByUser(ctx, userID)
	if err != nil {
		return store.Attachment{}, fmt.Errorf("sum bytes: %w", err)
	}
	if used+int64(len(processed)) > int64(MaxUploadBytesPerUser) {
		return store.Attachment{}, limitReached(i18n.Text(ctx, "Dung lượng tổng vượt quá 100MB. Xoá bớt file cũ."))
	}

	// Encrypt.
	master, err := files.LoadMasterKey()
	if err != nil {
		return store.Attachment{}, internalErr(filesText(ctx, err))
	}
	enc, err := files.Encrypt(processed, master)
	if err != nil {
		return store.Attachment{}, internalErr(i18n.Text(ctx, "Lỗi mã hoá file"))
	}

	// Write to disk. The segment is the device id when filed, or the reserved
	// inbox segment when not.
	root := files.PrivateUploadRoot()
	fileBase := uuid.NewString() + ".enc"
	segment := InboxStorageSegment
	if in.DeviceID != nil {
		segment = *in.DeviceID
	}
	storagePath, err := files.WriteEncrypted(root, segment, fileBase, enc.Ciphertext)
	if err != nil {
		return store.Attachment{}, internalErr(i18n.Text(ctx, "Lỗi ghi file"))
	}

	// DB row. Best-effort cleanup if the insert fails.
	att, err := q.CreateAttachment(ctx, store.CreateAttachmentParams{
		ID:          auth.NewID(),
		UserId:      userID,
		DeviceId:    in.DeviceID,
		FileName:    in.FileName,
		StoragePath: storagePath,
		FileType:    mime,
		FileSize:    int32(len(processed)), //nolint:gosec // bounded by MaxAttachmentBytes
		Iv:          enc.IV,
		WrappedKey:  enc.WrappedKey,
		Description: in.Description,
	})
	if err != nil {
		_ = files.DeleteEncrypted(root, storagePath)
		return store.Attachment{}, fmt.Errorf("create attachment: %w", err)
	}
	return att, nil
}

// NormalizeDescription applies the same normalization the upload path uses for
// the multipart `description` field: trim, and treat blank as "no description"
// (SQL NULL). So PATCHing `""`, `"   "` or `null` all clear it, and a client can
// reuse its upload-time encoding verbatim.
func NormalizeDescription(raw *string) *string {
	if raw == nil {
		return nil
	}
	v := strings.TrimSpace(*raw)
	if v == "" {
		return nil
	}
	return &v
}

// UpdateDescription rewrites one attachment's description.
//
// Ownership is enforced inside the query on the row's stored owner
// (`a."userId" = $2`, migration 0018) — the same check GetAttachmentByID uses,
// so this works for an inbox item as well as a filed one. Someone else's
// attachment therefore matches no row and comes back as notFound, i.e. HTTP 404
// and never 403: the endpoint must not confirm that an id exists for a user who
// does not own it (matching downloadFileHandler). The field surface is still
// description-only; filing is POST /api/v1/attachments/{id}/file.
func UpdateDescription(ctx context.Context, db *pgxpool.Pool, userID, attachmentID string, description *string) (store.Attachment, error) {
	att, err := store.New(db).UpdateAttachmentDescription(ctx, store.UpdateAttachmentDescriptionParams{
		ID:          attachmentID,
		UserId:      userID,
		Description: description,
	})
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return store.Attachment{}, notFound(i18n.Text(ctx, "Không tìm thấy file"))
		}
		return store.Attachment{}, fmt.Errorf("update attachment description: %w", err)
	}
	return att, nil
}

// Delete removes the attachment row and its on-disk blob. The blob removal
// is best-effort: if the file is already missing we still drop the DB row.
//
// The query is owner-scoped directly on "userId" (migration 0018), so an inbox
// item is deleted exactly like a filed one — the row and, normally, its blob.
func Delete(ctx context.Context, db *pgxpool.Pool, userID, attachmentID string) error {
	q := store.New(db)
	att, err := q.DeleteAttachment(ctx, store.DeleteAttachmentParams{
		ID:     attachmentID,
		UserId: userID,
	})
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return notFound(i18n.Text(ctx, "Không tìm thấy file"))
		}
		return fmt.Errorf("delete attachment: %w", err)
	}
	if rmErr := files.DeleteEncrypted(files.PrivateUploadRoot(), att.StoragePath); rmErr != nil {
		slog.Warn("attachment blob remove failed",
			"err", rmErr, "attachmentId", attachmentID, "storagePath", att.StoragePath)
	}
	return nil
}

// decryptAttachment reads + decrypts an owned attachment's blob into memory.
// Plaintext bytes never touch disk (matching OpenStream). Returns notFound on
// any miss / decrypt failure to avoid leaking which IDs exist. Shared by
// OpenStream (file download) and the AI extraction service.
//
// i18n note: `services.ExtractReceipt` (AI, wave 4) reuses this function, so the
// attachment-domain notFound below is reachable from POST /api/v1/ai/extract-receipt
// and now follows that request's language. It is the one message the AI endpoint
// gets from a converted domain; everything the AI service owns is still
// Vietnamese and stays that way until wave 4. `handlers/ai.go` and
// `services/ai_extract.go` were deliberately left untouched.
func decryptAttachment(ctx context.Context, db *pgxpool.Pool, userID, attachmentID string) (plain []byte, mime, name string, err error) {
	att, gerr := GetAttachmentForUser(ctx, db, userID, attachmentID)
	if gerr != nil {
		return nil, "", "", gerr
	}
	root := files.PrivateUploadRoot()
	ct, rerr := files.ReadEncrypted(root, att.StoragePath)
	if rerr != nil {
		return nil, "", "", notFound(i18n.Text(ctx, "Không tìm thấy file"))
	}
	master, merr := files.LoadMasterKey()
	if merr != nil {
		return nil, "", "", internalErr(filesText(ctx, merr))
	}
	plainBytes, derr := files.Decrypt(ct, att.Iv, att.WrappedKey, master)
	if derr != nil {
		// Decrypt failure (key mismatch / tag fail) → leak nothing, treat as
		// missing.
		return nil, "", "", notFound(i18n.Text(ctx, "Không tìm thấy file"))
	}
	return plainBytes, att.FileType, att.FileName, nil
}

// OpenStream returns the decrypted bytes of the attachment as an
// io.ReadCloser, plus the MIME and original filename. ≤5 MB files are
// buffered in memory — well within the request budget.
func OpenStream(ctx context.Context, db *pgxpool.Pool, userID, attachmentID string) (mime, name string, body io.ReadCloser, size int64, err error) {
	plain, ft, fn, derr := decryptAttachment(ctx, db, userID, attachmentID)
	if derr != nil {
		return "", "", nil, 0, derr
	}
	return ft, fn, io.NopCloser(bytes.NewReader(plain)), int64(len(plain)), nil
}
