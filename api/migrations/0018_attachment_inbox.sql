-- Warrly — the capture-first inbox: an attachment may exist before it has a
-- device (roadmap #12, the prerequisite for email-in / share-sheet / bulk).
--
-- ── Why "deviceId" becomes nullable ─────────────────────────────────────────
--
-- At the counter the user knows they bought something but not which device row
-- it belongs to — or there is no row yet (a gift, a second-hand purchase, a
-- household item). Requiring a device at upload is why receipts get abandoned.
-- The inbox is deliberately NOT a second file table: an inbox item is the same
-- "Attachment" row, same AES-256-GCM blob, same MIME whitelist and same 5 MB /
-- 100 MB accounting. The only difference is that its "deviceId" is NULL.
--
-- The FK stays. `ON DELETE CASCADE` on "deviceId" is untouched: a device that
-- disappears still takes its filed attachments with it, and an inbox item —
-- which references no device — is unaffected by that delete.
--
-- Existing rows are unaffected: every one of them already has a device, so
-- `ALTER COLUMN ... DROP NOT NULL` accepts the current data as-is and changes
-- nothing about how it is read, counted or deleted.
--
-- ── Why a new "userId" column is also required ─────────────────────────────
--
-- This is the one addition the frozen endpoint contract implies but does not
-- spell out, and it is not optional.
--
-- Attachment ownership used to be DERIVED, never stored:
--
--     "Attachment"."deviceId" → "Device"."userId"
--
-- The moment "deviceId" may be NULL, an inbox row has no path to a user at all.
-- `GET /api/v1/inbox` is defined as "the caller's unassigned attachments" and
-- `POST /api/v1/attachments/{id}/file` must answer 404 for "not the caller's",
-- so an inbox row NEEDS a stored owner. Without this column the feature cannot
-- be implemented safely — the alternative would be trusting a client-supplied
-- id or parsing the on-disk path, both of which are authorisation bugs.
--
-- So the owner is stored directly on every row, filed or not:
--
--   * "userId" NOT NULL, FK to "User" with ON DELETE CASCADE (same as
--     "Device"."userId"): deleting an account still deletes its blobs' rows.
--   * Existing rows are BACKFILLED from their device's owner before NOT NULL is
--     applied. That is a one-time data change with no behavioural effect: the
--     value is exactly the owner the old join already resolved to.
--   * `deviceId` still says where the attachment is filed (NULL = inbox).
--     `userId` says who owns it. The two are independent on purpose: filing an
--     inbox item to a device does not move ownership.
--
-- The reader-visible ownership rule becomes `a."userId" = :currentUser` for
-- every attachment, filed or not. The device join in the list-by-device query
-- is kept as a second, harmless guard.
--
-- ── Storage path ───────────────────────────────────────────────────────────
--
-- Blobs stay under PRIVATE_UPLOAD_ROOT. Filed rows keep the historical
-- `<deviceId>/<uuid>.enc` layout; inbox rows use the reserved segment
-- `_inbox/<uuid>.enc`. Filing (or returning) an item renames the blob to the new
-- segment so the path keeps matching the row — `storagePath` is part of the
-- backup payload and must remain meaningful after a restore. `_inbox` cannot
-- collide with a real device id: device ids are generated by the server (cuid)
-- and the backup importer now refuses a payload device named `_inbox`.
--
-- ── Rollback ───────────────────────────────────────────────────────────────
--
-- Down deletes inbox rows (they cannot exist in the pre-0018 schema) and then
-- re-applies NOT NULL to "deviceId". Destructive, like every schema rollback;
-- goose refuses `down` without WV_ALLOW_DESTRUCTIVE=1.

-- +goose Up
-- +goose StatementBegin

ALTER TABLE public."Attachment"
    ALTER COLUMN "deviceId" DROP NOT NULL;

ALTER TABLE public."Attachment"
    ADD COLUMN IF NOT EXISTS "userId" text;

-- Backfill the owner of every pre-existing (device-filed) row from the device
-- that already governed its access. No row is written for the inbox: it did not
-- exist before this migration.
UPDATE public."Attachment" a
SET "userId" = d."userId"
FROM public."Device" d
WHERE a."deviceId" = d.id
  AND a."userId" IS NULL;

ALTER TABLE public."Attachment"
    ALTER COLUMN "userId" SET NOT NULL;

ALTER TABLE public."Attachment"
    ADD CONSTRAINT "Attachment_userId_fkey"
    FOREIGN KEY ("userId") REFERENCES public."User"(id)
    ON UPDATE CASCADE ON DELETE CASCADE;

CREATE INDEX "Attachment_userId_idx"
    ON public."Attachment" USING btree ("userId");

-- The inbox list is `WHERE "userId" = $1 AND "deviceId" IS NULL ORDER BY
-- "uploadedAt" DESC`. A partial index keeps that read cheap without paying for
-- every filed row (the overwhelming majority).
CREATE INDEX "Attachment_inbox_idx"
    ON public."Attachment" USING btree ("userId", "uploadedAt" DESC)
    WHERE "deviceId" IS NULL;

-- +goose StatementEnd

-- +goose Down
-- +goose StatementBegin

DROP INDEX IF EXISTS public."Attachment_inbox_idx";
DROP INDEX IF EXISTS public."Attachment_userId_idx";

ALTER TABLE public."Attachment"
    DROP CONSTRAINT IF EXISTS "Attachment_userId_fkey";

-- Inbox rows cannot be represented by the pre-0018 schema (no device, no
-- "userId" column after the drop). A rollback therefore discards them.
DELETE FROM public."Attachment" WHERE "deviceId" IS NULL;

ALTER TABLE public."Attachment"
    ALTER COLUMN "deviceId" SET NOT NULL;

ALTER TABLE public."Attachment"
    DROP COLUMN IF EXISTS "userId";

-- +goose StatementEnd
